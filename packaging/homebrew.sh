#!/usr/bin/env bash
# Print the Homebrew formula for a release.
#
#   packaging/homebrew.sh VERSION DISTDIR > Formula/cantainer.rb
#
# The formula installs the prebuilt static binary from the GitHub release. It is Linux-only:
# cants need a Linux kernel (Homebrew on Linux, WSL).
set -euo pipefail

version="${1:?usage: packaging/homebrew.sh VERSION DISTDIR}"
dist="${2:?missing DISTDIR}"
base="https://github.com/cantainer/cantainer/releases/download/v$version"

sha() { sha256sum "$dist/cant-v$version-$1-unknown-linux-musl.tar.gz" | cut -d' ' -f1; }
sha_x86_64="$(sha x86_64)"
sha_aarch64="$(sha aarch64)"

cat <<EOF
# Generated by packaging/homebrew.sh in github.com/cantainer/cantainer. Don't edit by hand.
class Cantainer < Formula
  desc "Run every executable as a least-privilege capsule"
  homepage "https://github.com/cantainer/cantainer"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on :linux

  on_linux do
    on_intel do
      url "$base/cant-v$version-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$sha_x86_64"
    end
    on_arm do
      url "$base/cant-v$version-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$sha_aarch64"
    end
  end

  def install
    bin.install "cant"
    doc.install "README.md", "CHANGELOG.md"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/cant --version")
  end
end
EOF
