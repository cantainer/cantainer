#!/usr/bin/env bash
# Write the AUR package `cantainer-bin` (PKGBUILD and .SRCINFO) for a release.
#
#   packaging/aur.sh VERSION DISTDIR OUTDIR
#
# The package installs the prebuilt static binary from the GitHub release. .SRCINFO is written
# directly, because makepkg (which normally generates it) only exists on Arch.
set -euo pipefail
umask 022

version="${1:?usage: packaging/aur.sh VERSION DISTDIR OUTDIR}"
dist="${2:?missing DISTDIR}"
out="${3:?missing OUTDIR}"
mkdir -p "$out"

# Arch versions can't contain '-'; '_' keeps pre-releases readable (pacman sorts them oddly
# either way, so pre-releases shouldn't be pushed to the AUR).
pkgver="${version//-/_}"
desc="Run every executable as a least-privilege capsule"
url="https://github.com/cantainer/cantainer"
base="$url/releases/download/v$version"

sha() { sha256sum "$dist/cant-v$version-$1-unknown-linux-musl.tar.gz" | cut -d' ' -f1; }
sha_x86_64="$(sha x86_64)"
sha_aarch64="$(sha aarch64)"

cat > "$out/PKGBUILD" <<EOF
# Maintainer: Arie Radle <arie dot radle at gmail dot com>
# Generated by packaging/aur.sh in $url. Don't edit by hand.
pkgname=cantainer-bin
pkgver=$pkgver
pkgrel=1
pkgdesc="$desc"
arch=('x86_64' 'aarch64')
url="$url"
license=('MIT OR Apache-2.0')
provides=('cantainer')
conflicts=('cantainer')
options=('!strip' '!debug')
source_x86_64=("$base/cant-v$version-x86_64-unknown-linux-musl.tar.gz")
source_aarch64=("$base/cant-v$version-aarch64-unknown-linux-musl.tar.gz")
sha256sums_x86_64=('$sha_x86_64')
sha256sums_aarch64=('$sha_aarch64')

package() {
  cd "cant-v$version-\$CARCH-unknown-linux-musl"
  install -Dm755 cant "\$pkgdir/usr/bin/cant"
  install -dm755 "\$pkgdir/etc/cantainer/cants"
  install -Dm644 -t "\$pkgdir/usr/share/doc/cantainer" README.md CHANGELOG.md
  install -Dm644 -t "\$pkgdir/usr/share/licenses/\$pkgname" LICENSE-MIT LICENSE-APACHE
}
EOF

cat > "$out/.SRCINFO" <<EOF
pkgbase = cantainer-bin
	pkgdesc = $desc
	pkgver = $pkgver
	pkgrel = 1
	url = $url
	arch = x86_64
	arch = aarch64
	license = MIT OR Apache-2.0
	provides = cantainer
	conflicts = cantainer
	options = !strip
	options = !debug
	source_x86_64 = $base/cant-v$version-x86_64-unknown-linux-musl.tar.gz
	sha256sums_x86_64 = $sha_x86_64
	source_aarch64 = $base/cant-v$version-aarch64-unknown-linux-musl.tar.gz
	sha256sums_aarch64 = $sha_aarch64

pkgname = cantainer-bin
EOF
echo "$out/PKGBUILD"
